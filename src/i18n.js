const LANGS = { en: EN, hy: HY, ru: RU }
export const LANG_ORDER = ['en', 'hy', 'ru']
export const LANG_LABEL = { en: 'EN', hy: 'ՀԱՅ', ru: 'RU' }

// Word forms for "N cities / places / days" per language, so counts read
// naturally instead of always using the English plural rule.
const PLURALS = {
  en: { cities: ['city', 'cities'], places: ['place', 'places'], days: ['day', 'days'] },
  hy: { cities: ['քաղաք'], places: ['վայր'], days: ['օր'] },
  ru: {
    cities: ['город', 'города', 'городов'],
    places: ['место', 'места', 'мест'],
    days: ['день', 'дня', 'дней'],
  },
}

export function labelsFor(lang) {
  return LANGS[lang] || EN
}

// "3 places" / "3 места" — Armenian is invariant, Russian takes one of three
// forms depending on the last digits of n, English just singular/plural.
export function pluralize(lang, n, key) {
  const forms = (PLURALS[lang] || PLURALS.en)[key]
  if (forms.length === 1) return `${n} ${forms[0]}`
  if (lang === 'ru') {
    const mod10 = n % 10
    const mod100 = n % 100
    if (mod10 === 1 && mod100 !== 11) return `${n} ${forms[0]}`
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return `${n} ${forms[1]}`
    return `${n} ${forms[2]}`
  }
  return `${n} ${forms[n === 1 ? 0 : 1]}`
}
